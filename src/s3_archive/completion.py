"""Render a static bash completion script from the argparse parser.

The words are fixed: subcommands and options; every positional is an S3 URL,
so there is nothing to complete and nothing is read from config. A static
script that never runs Python covers that, and generating it from the parser
keeps it in step. ``make completions`` writes
``completions/s3-archive.bash`` through :func:`main`;
``tests/test_completion.py`` fails when the committed copy drifts.

The parser walk reads argparse's ``_actions`` and ``_SubParsersAction``:
private, but stable for over a decade, and only ever read here, at generate
and test time.

Imports ``cli`` (for ``_build_parser`` and ``_utf8_streams``); nothing
imports this module.
"""

from __future__ import annotations

import argparse
import sys

from s3_archive.cli import _build_parser, _utf8_streams

_HEADER = """\
# bash completion for {prog}
# Generated by `make completions` from the argparse parser; do not edit.
"""


def _options(parser: argparse.ArgumentParser) -> tuple[list[str], list[str]]:
    """Every option string the parser takes, and those that take a value."""
    words: list[str] = []
    valued: list[str] = []
    for action in parser._actions:
        words.extend(action.option_strings)
        if action.option_strings and action.nargs != 0:
            valued.extend(action.option_strings)
    return words, valued


def _subcommands(parser: argparse.ArgumentParser) -> dict[str, argparse.ArgumentParser]:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return dict(action.choices)
    return {}


def render_bash(parser: argparse.ArgumentParser) -> str:
    """The completion script for ``parser``: subcommands, then each one's options."""
    prog = parser.prog
    func = "_" + prog.replace("-", "_")
    top_options, valued = _options(parser)
    subcommands = _subcommands(parser)
    per_command = {name: _options(sub) for name, sub in subcommands.items()}
    for _, sub_valued in per_command.values():
        valued.extend(v for v in sub_valued if v not in valued)

    cases = "\n".join(
        f'        {name}) words="{" ".join(words)}" ;;' for name, (words, _) in per_command.items()
    )
    names = " ".join(subcommands)
    return (
        _HEADER.format(prog=prog)
        + f"""
{func}() {{
    local cur=${{COMP_WORDS[COMP_CWORD]}} prev=${{COMP_WORDS[COMP_CWORD-1]}}
    local cmd="" i

    # A value-taking option's argument is free text: offer nothing.
    case $prev in
        {"|".join(valued)}) return 0 ;;
    esac

    # The subcommand, if one was typed, skipping option values.
    for ((i = 1; i < COMP_CWORD; i++)); do
        case ${{COMP_WORDS[i]}} in
            {"|".join(valued)}) ((i++)) ;;
            {"|".join(subcommands)}) cmd=${{COMP_WORDS[i]}}; break ;;
        esac
    done

    local words
    case $cmd in
        "") words="{" ".join(top_options)}" ;;
{cases}
    esac
    if [[ -z $cmd && $cur != -* ]]; then
        words="{names}"
    fi
    mapfile -t COMPREPLY < <(compgen -W "$words" -- "$cur")
}}

complete -F {func} {prog}
"""
    )


def main() -> None:
    """Print the script for s3-archive's own parser (``make completions``)."""
    # The script is committed and read back as UTF-8 (tests/test_completion.py),
    # so its bytes must not follow the host locale the Makefile redirect runs in.
    _utf8_streams()
    sys.stdout.write(render_bash(_build_parser()))


if __name__ == "__main__":
    main()
